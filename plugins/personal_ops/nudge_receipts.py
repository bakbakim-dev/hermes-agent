def record_autopsy(
    receipt_id: str,
    *,
    reason: str,
    notes: Optional[str] = None,
) -> Dict[str, Any]:
    """Run an autopsy on a bad nudge and persist a reviewed-test proposal."""
    _ensure_tables()
    autopsy_data = {
        "reason": reason,
        "notes": notes,
        "recorded_at": datetime.now(timezone.utc).isoformat(),
    }
    conn = sqlite3.connect(DB_PATH, timeout=5.0)
    cur = conn.cursor()
    cur.execute(
        "SELECT event_type, task_id, task_content, trigger, assumptions FROM nudge_receipts WHERE id = ?",
        (receipt_id,),
    )
    row = cur.fetchone()
    if not row:
        conn.close()
        return {"error": "receipt_not_found"}

    autopsy_data["original"] = {
        "event_type": row[0],
        "task_id": row[1],
        "task_content": row[2],
        "trigger": row[3],
        "assumptions": json.loads(row[4]) if row[4] else None,
    }
    cur.execute(
        "UPDATE nudge_receipts SET autopsy = ?, outcome = 'bad_nudge' WHERE id = ?",
        (json.dumps(autopsy_data), receipt_id),
    )
    conn.commit()
    conn.close()
    _write_regression_proposal(receipt_id, autopsy_data)
    return autopsy_data


def _write_regression_proposal(receipt_id: str, autopsy: Dict[str, Any]) -> None:
    original = autopsy.get("original", {})
    proposal = {
        "proposal_id": "bad_nudge_" + hashlib.sha256(receipt_id.encode("utf-8")).hexdigest()[:12],
        "receipt_id": receipt_id,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "kind": "bad_nudge_regression_proposal",
        "reason": autopsy.get("reason", "unknown"),
        "notes": autopsy.get("notes"),
        "task_content": original.get("task_content", "unknown_task"),
        "event_type": original.get("event_type", "unknown_event"),
        "assumptions": original.get("assumptions") or {},
        "expected_behavior": "Create a reviewed regression test that blocks this nudge in the same context.",
    }
    BAD_NUDGE_PROPOSALS_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(BAD_NUDGE_PROPOSALS_PATH, "a", encoding="utf-8") as f:
        f.write(json.dumps(proposal, sort_keys=True) + "\n")


def get_recent_receipts(limit: int = 20) -> List[Dict[str, Any]]:
    """Return recent nudge receipts, newest first."""
    _ensure_tables()
    conn = sqlite3.connect(DB_PATH, timeout=5.0)
    cur = conn.cursor()
    cur.execute(
        """
        SELECT id, created_at, event_type, task_id, task_content, trigger,
               outcome, autopsy, telegram_message_id
        FROM nudge_receipts
        ORDER BY created_at DESC
        LIMIT ?
        """,
        (limit,),
    )
    rows = cur.fetchall()
    conn.close()
    return [
        {
            "id": row[0],
            "created_at": row[1],
            "event_type": row[2],
            "task_id": row[3],
            "task_content": row[4],
            "trigger": row[5],
            "outcome": row[6],
            "autopsy": json.loads(row[7]) if row[7] else None,
            "telegram_message_id": row[8],
        }
        for row in rows
    ]


def get_bad_nudge_stats() -> Dict[str, Any]:
    """Return aggregate statistics on bad nudges."""
    _ensure_tables()
    conn = sqlite3.connect(DB_PATH, timeout=5.0)
    cur = conn.cursor()
    cur.execute("SELECT COUNT(*) FROM nudge_receipts")
    total = cur.fetchone()[0]
    cur.execute("SELECT COUNT(*) FROM nudge_receipts WHERE outcome = 'bad_nudge'")
    bad = cur.fetchone()[0]
    cur.execute("SELECT autopsy FROM nudge_receipts WHERE outcome = 'bad_nudge' AND autopsy IS NOT NULL")
    reason_counts: Dict[str, int] = {}
    for (autopsy_json,) in cur.fetchall():
        try:
            data = json.loads(autopsy_json)
            reason = data.get("reason", "unknown")
            reason_counts[reason] = reason_counts.get(reason, 0) + 1
        except Exception:
            pass
    conn.close()
    return {
        "total_nudges": total,
        "bad_nudges": bad,
        "bad_rate": bad / max(1, total),
        "reason_breakdown": reason_counts,
    }
