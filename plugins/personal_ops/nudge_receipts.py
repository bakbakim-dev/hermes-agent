HERMES_HOME = Path(os.getenv("HERMES_HOME", str(Path.home() / ".hermes")))
DB_PATH = HERMES_HOME / "personal_ops" / "event_log.db"

# Kept for backward compatibility with old tests/config, but runtime no longer
